/** HTTP methods supported by the route handlers. */
export type HttpMethod = "get" | "post" | "put" | "patch" | "delete";

/** Authentication requirement documented per operation. */
export type AuthMode = "none" | "optional" | "bearer" | "admin";

/** Parameter definition (query or path). */
export interface ParamSpec {
  name: string;
  in?: "query" | "path";
  required?: boolean;
  type?: "string" | "int" | "number" | "bool" | "csv";
  description?: string;
  enum?: string[];
  default?: string | number | boolean;
}

/** One documented API operation. */
export interface ApiOperation {
  method: HttpMethod;
  /** OpenAPI path, e.g. `/api/spots/{id}`. */
  path: string;
  /** Route file relative to the repository root (used for JSDoc). */
  file: string;
  tag: string;
  operationId: string;
  summary: string;
  description: string;
  auth: AuthMode;
  params?: ParamSpec[];
  body?: z.ZodType;
  bodyDescription?: string;
  successStatus?: number;
  responseRef?: string;
  responseDescription?: string;
  deprecated?: boolean;
}

const q = (
  name: string,
  type: ParamSpec["type"] = "string",
  description?: string,
  extra: Omit<ParamSpec, "name" | "type" | "description" | "in"> = {},
): ParamSpec => ({ name, in: "query", type, description, ...extra });

const pathParam = (name: string, description: string): ParamSpec => ({
  name,
  in: "path",
  required: true,
  type: "string",
  description,
});

