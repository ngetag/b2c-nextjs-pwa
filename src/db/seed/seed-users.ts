/** Referensi kolom `excluded.<column>` untuk upsert idempoten. */
function excluded(column: string) {
  return sql.raw(`excluded."${column}"`);
}

async function seedWithDrizzle() {
  const connectionString = process.env.DATABASE_URL ?? DEFAULT_DATABASE_URL;
  const pool = new Pool({ connectionString });
  const db = drizzle({ client: pool });
  const seedIds = SEED_CUSTOMERS.map((customer) => String(customer.id));

  try {
    await db.transaction(async (tx) => {
      await tx
        .insert(interests)
        .values(
          interestFixtures.map((interest, index) => ({
            id: interest.id,
            label: interest.label,
            slug: interest.slug,
            sortOrder: index,
          })),
        )
        .onConflictDoNothing();

      await tx
        .insert(tags)
        .values(tagFixtures)
        .onConflictDoNothing();

      if (reset) {
        await tx
          .delete(customerFavoriteTags)
          .where(inArray(customerFavoriteTags.customerId, seedIds));
        await tx
          .delete(customerInterests)
          .where(inArray(customerInterests.customerId, seedIds));
        await tx.delete(customers).where(inArray(customers.id, seedIds));
        console.log(`Reset: ${seedIds.length} customer seed dihapus.`);
      }

      await tx
        .insert(customers)
        .values(SEED_CUSTOMERS)
        .onConflictDoUpdate({
          target: customers.id,
          set: {
            name: excluded("name"),
            email: excluded("email"),
            avatarUrl: excluded("avatar_url"),
            role: excluded("role"),
            bio: excluded("bio"),
            badges: excluded("badges"),
            preferences: excluded("preferences"),
            points: excluded("points"),
            joinedAt: excluded("joined_at"),
            updatedAt: excluded("updated_at"),
          },
        });

      if (SEED_CUSTOMER_INTERESTS.length > 0) {
        await tx
          .insert(customerInterests)
          .values(SEED_CUSTOMER_INTERESTS)
          .onConflictDoNothing();
      }

      if (SEED_CUSTOMER_FAVORITE_TAGS.length > 0) {
        await tx
          .insert(customerFavoriteTags)
          .values(SEED_CUSTOMER_FAVORITE_TAGS)
          .onConflictDoNothing();
      }
    });

    console.log(
      `Seed selesai: ${SEED_CUSTOMERS.length} customer, ` +
        `${SEED_CUSTOMER_INTERESTS.length} interest link, ` +
        `${SEED_CUSTOMER_FAVORITE_TAGS.length} favorite tag link.`,
    );
  } finally {
    await pool.end();
  }
}

async function main() {
  const errors = validateSeed();
  if (errors.length > 0) {
    console.error("Seed tidak valid:");
    for (const error of errors) console.error(` - ${error}`);
    process.exitCode = 1;
    return;
  }

  if (emitSql) {
    process.stdout.write(buildSeedSql());
    return;
  }

  printSummary();

  if (dryRun) {
    console.log(
      "\nDry run: data valid, tidak ada koneksi database yang dibuka.\n",
    );
    return;
  }

  await seedWithDrizzle();
}

main().catch((error) => {
  console.error("Seed gagal:", error);
  process.exitCode = 1;
});
