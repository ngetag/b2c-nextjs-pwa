// ============================================================================
// SQL generator (idempoten, dipakai untuk `--sql` / psql manual)
// ============================================================================

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlJson(value: unknown): string {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

function sqlNullableString(value: string | null | undefined): string {
  return value === null || value === undefined ? "NULL" : sqlString(value);
}

function sqlNullableTimestamp(value: Date | null | undefined): string {
  return value === null || value === undefined
    ? "NULL"
    : sqlString(value.toISOString());
}

export function buildSeedSql(): string {
  const lines: string[] = [];
  lines.push("-- NgeTag — seed user (generated by src/db/seed/seed-users.ts)");
  lines.push("-- Idempoten: aman dijalankan berulang kali.");
  lines.push("BEGIN;");
  lines.push("");

  lines.push(
    'INSERT INTO "interests" ("id", "label", "slug", "sort_order") VALUES',
    interestFixtures
      .map(
        (interest, index) =>
          `  (${sqlString(interest.id)}, ${sqlString(interest.label)}, ${sqlString(interest.slug)}, ${index})`,
      )
      .join(",\n"),
    "ON CONFLICT (\"id\") DO NOTHING;",
    "",
  );

  lines.push(
    'INSERT INTO "tags" ("id", "slug", "name", "category", "icon_name", "trending_score") VALUES',
    tagFixtures
      .map(
        (tag) =>
          `  (${sqlString(tag.id)}, ${sqlString(tag.slug)}, ${sqlString(tag.name)}, ${sqlString(tag.category)}, ${sqlNullableString(tag.iconName)}, ${String(tag.trendingScore ?? 0)})`,
      )
      .join(",\n"),
    "ON CONFLICT (\"id\") DO NOTHING;",
    "",
  );

  const customerValues = SEED_CUSTOMERS.map((customer) => {
    const columns = [
      sqlString(String(customer.id)),
      sqlString(String(customer.name)),
      sqlString(String(customer.email)),
      sqlNullableString(customer.avatarUrl),
      sqlString(String(customer.role ?? "customer")),
      sqlNullableString(customer.bio),
      sqlJson(customer.badges ?? []),
      customer.preferences === null ? "NULL" : sqlJson(customer.preferences),
      String(customer.points ?? 0),
      sqlString((customer.joinedAt ?? new Date()).toISOString()),
      sqlNullableTimestamp(customer.updatedAt),
    ];
    return `  (${columns.join(", ")})`;
  });

  lines.push(
    'INSERT INTO "customers" ("id", "name", "email", "avatar_url", "role", "bio", "badges", "preferences", "points", "joined_at", "updated_at") VALUES',
    customerValues.join(",\n"),
    `ON CONFLICT ("id") DO UPDATE SET
  "name" = EXCLUDED."name",
  "email" = EXCLUDED."email",
  "avatar_url" = EXCLUDED."avatar_url",
  "role" = EXCLUDED."role",
  "bio" = EXCLUDED."bio",
  "badges" = EXCLUDED."badges",
  "preferences" = EXCLUDED."preferences",
  "points" = EXCLUDED."points",
  "joined_at" = EXCLUDED."joined_at",
  "updated_at" = EXCLUDED."updated_at";`,
    "",
  );

  if (SEED_CUSTOMER_INTERESTS.length > 0) {
    lines.push(
      'INSERT INTO "customer_interests" ("customer_id", "interest_id") VALUES',
      SEED_CUSTOMER_INTERESTS.map(
        (link) =>
          `  (${sqlString(link.customerId)}, ${sqlString(link.interestId)})`,
      ).join(",\n"),
      "ON CONFLICT DO NOTHING;",
      "",
    );
  }

  if (SEED_CUSTOMER_FAVORITE_TAGS.length > 0) {
    lines.push(
      'INSERT INTO "customer_favorite_tags" ("customer_id", "tag_id") VALUES',
      SEED_CUSTOMER_FAVORITE_TAGS.map(
        (link) => `  (${sqlString(link.customerId)}, ${sqlString(link.tagId)})`,
      ).join(",\n"),
      "ON CONFLICT DO NOTHING;",
      "",
    );
  }

  lines.push("COMMIT;");
  lines.push("");
  return lines.join("\n");
}

