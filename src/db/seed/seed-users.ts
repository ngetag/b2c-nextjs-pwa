/**
 * Runner seed user NgeTag.
 *
 * Perintah:
 *   npm run db:seed                 # upsert 16 customer + relasi ke PostgreSQL
 *   npm run db:seed -- --dry-run    # validasi + ringkasan, tanpa koneksi DB
 *   npm run db:seed -- --reset      # hapus dulu data seed, lalu insert ulang
 *   npm run db:seed -- --sql        # cetak SQL idempoten (bisa disimpan ke .sql)
 *
 * Koneksi memakai DATABASE_URL, dengan fallback sama seperti `drizzle.config.ts`.
 */

import "dotenv/config";
import { inArray, sql } from "drizzle-orm";
import { drizzle } from "drizzle-orm/node-postgres";
import { Pool } from "pg";
import { interests as interestFixtures } from "@/data/fixtures/interests";
import { tags as tagFixtures } from "@/data/fixtures/tags";
import {
  customers,
  customerFavoriteTags,
  customerInterests,
  interests,
  tags,
} from "@/db/schema";
import {
  SEED_CUSTOMERS,
  SEED_CUSTOMER_FAVORITE_TAGS,
  SEED_CUSTOMER_INTERESTS,
  SEED_CUSTOMER_PROFILES,
  SEED_USER_STATS,
  SEED_VARIANTS,
  validateSeed,
} from "./user-seed";

const DEFAULT_DATABASE_URL =
  "postgresql://ap_admin:ap_secret@localhost:5432/ngetag";

const flags = new Set(process.argv.slice(2));
const dryRun = flags.has("--dry-run");
const reset = flags.has("--reset");
const emitSql = flags.has("--sql");

